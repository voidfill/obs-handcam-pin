#!/usr/bin/env bash
# Download the libobs public headers for the pinned OBS release into vendor/libobs.
# build.sh runs this automatically when the headers are missing or OBS_VERSION changed.
# Usage: scripts/fetch-obs-headers.sh [tag]   (default: contents of ./OBS_VERSION)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TAG="${1:-$(tr -d '[:space:]' < "$ROOT/OBS_VERSION")}"
DEST="$ROOT/vendor/libobs"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "Fetching libobs headers from OBS $TAG..."
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$TAG" --filter=blob:none --sparse \
  https://github.com/obsproject/obs-studio.git "$TMP/obs" 2> >(grep -v 'is not a commit' >&2)
git -C "$TMP/obs" sparse-checkout set libobs

# Stage into a temp dir and swap it in at the end, so an interrupted fetch
# never leaves a half-populated vendor/libobs behind.
STAGE="$TMP/libobs"
mkdir -p "$STAGE"
( cd "$TMP/obs/libobs" && find . -name '*.h' -print0 | \
  while IFS= read -r -d '' f; do mkdir -p "$STAGE/$(dirname "$f")"; cp "$f" "$STAGE/$f"; done )
# obsconfig.h is generated by OBS's CMake; plugins only need it to exist.
cat > "$STAGE/obsconfig.h" <<'H'
#pragma once
/* Static stand-in for the CMake-generated obsconfig.h (not used by plugins). */
#define OBS_DATA_PATH "data"
#define OBS_PLUGIN_PATH "obs-plugins"
#define OBS_PLUGIN_DESTINATION "obs-plugins"
#define OBS_INSTALL_PREFIX ""
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
H
cp "$TMP/obs/COPYING" "$STAGE/COPYING"
echo "$TAG" > "$STAGE/OBS_VERSION"

rm -rf "$DEST"
mkdir -p "$(dirname "$DEST")"
mv "$STAGE" "$DEST"
echo "libobs headers for OBS $TAG -> vendor/libobs"
