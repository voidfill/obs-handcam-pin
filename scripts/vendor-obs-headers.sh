#!/usr/bin/env bash
# Re-vendor the libobs public headers from a pinned OBS Studio release.
# Usage: scripts/vendor-obs-headers.sh [tag]   (default: 31.1.2)
set -euo pipefail
TAG="${1:-31.1.2}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
git clone --quiet --depth 1 --branch "$TAG" --filter=blob:none --sparse \
  https://github.com/obsproject/obs-studio.git "$TMP/obs"
git -C "$TMP/obs" sparse-checkout set libobs
rm -rf "$ROOT/vendor/libobs"
mkdir -p "$ROOT/vendor/libobs"
( cd "$TMP/obs/libobs" && find . -name '*.h' -print0 | \
  while IFS= read -r -d '' f; do mkdir -p "$ROOT/vendor/libobs/$(dirname "$f")"; cp "$f" "$ROOT/vendor/libobs/$f"; done )
# obsconfig.h is generated by OBS's CMake; plugins only need it to exist.
cat > "$ROOT/vendor/libobs/obsconfig.h" <<'H'
#pragma once
/* Static stand-in for the CMake-generated obsconfig.h (not used by plugins). */
#define OBS_DATA_PATH "data"
#define OBS_PLUGIN_PATH "obs-plugins"
#define OBS_PLUGIN_DESTINATION "obs-plugins"
#define OBS_INSTALL_PREFIX ""
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
H
cp "$TMP/obs/COPYING" "$ROOT/vendor/libobs/COPYING"
echo "$TAG" > "$ROOT/vendor/libobs/OBS_VERSION"
echo "Vendored libobs headers from OBS $TAG"
